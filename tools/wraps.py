"""wraps.py - thin-wrapper family sweep.

Shape (85+ units in the 17..32 band):
    55 8B EC                 push bp; mov bp,sp
    (FF 76 xx | 6A xx | 68 xx xx)+     push a parameter / a constant
    (90)? 0E E8 <rel16>      push cs; call far   (MSC's far call to a known target)
    C9 (CA|C2) <imm16>       leave; retf
The pushed parameters are the wrapper's own arguments; the call target is a
relocation in our object, so match.py masks those bytes.

Generated C:  extern void __far __pascal CALLEE(...);
              void __far __pascal w<addr>(int p0, ...) { CALLEE(args...); }
"""
import csv
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = open(os.path.join(ROOT, "..", "giten", "DDS98", "DDS98.EXE"), "rb").read()[896 * 16:339735]
FLAGS = "/G1 /AM /Gs /Os"

units = {int(r["linear"], 16): (r["va"], int(r["size"]))
         for r in csv.DictReader(open(os.path.join(ROOT, "ground_truth", "units.csv")))}
ledger = open(os.path.join(ROOT, "docs", "MATCHING.md"), encoding="utf-8").read()
done = {int(m.group(1), 16) * 16 + int(m.group(2), 16)
        for m in re.finditer(r"^\|\s*([0-9a-f]{4}):([0-9a-f]{4})\s*\|", ledger, re.M)}

# Two call forms occur in the binary:
#   E8 <rel16>          near call      -> generatable (callee is __near __pascal)
#   90 0E E8 <rel16>    push cs; call  -> NOT generatable: MSC always emits 9A for
#                                        a far call, so those units are skipped and
#                                        counted instead of silently mismatching.
PAT_NEAR = re.compile(rb"\x55\x8B\xEC"
                      rb"(?P<pushes>(?:\xFF\x76.|\x6A.|\x68....)+)"
                      rb"\xE8(?P<rel>..)"
                      rb"\xC9(?:\xCA|\xC2)(?P<imm>..)", re.S)
PAT_CS = re.compile(rb"\x55\x8B\xEC(?P<pushes>(?:\xFF\x76.|\x6A.|\x68....)+)"
                    rb"(?:\x90)?\x0E\xE8..\xC9(?:\xCA|\xC2)..", re.S)


def parse_pushes(p):
    out, i = [], 0
    while i < len(p):
        op = p[i]
        if op == 0xFF and p[i + 1] == 0x76:
            out.append(("param", p[i + 2])); i += 3
        elif op == 0x6A:
            out.append(("const", p[i + 1])); i += 2
        elif op == 0x68:
            out.append(("const", int.from_bytes(p[i + 1:i + 3], "little"))); i += 3
        else:
            return None
    return out


hits = []
skipped_cs = 0
for lin, (va, size) in units.items():
    if lin in done:
        continue
    b = IMG[lin - 0x10000: lin - 0x10000 + size]
    if b and PAT_CS.fullmatch(b):
        skipped_cs += 1
        continue
    m = PAT_NEAR.fullmatch(b) if b else None
    if not m:
        continue
    pushes = parse_pushes(m.group("pushes"))
    if not pushes:
        continue
    hits.append((va, m.end() - m.start(), pushes, m.group("imm")))

print(f"{len(hits)} generatable near-call wrappers ({skipped_cs} skipped: push-cs far-call form)")
if not hits:
    sys.exit(0)

lines = []
meta = []
stubs = set()
for va, size, pushes, imm in hits:
    # parameters of the wrapper itself: offsets 6, 8, 10 ... in push order
    offs = [v for k, v in pushes if k == "param"]
    nparams = (max(offs) - 6) // 2 + 1 if offs else 0
    names = ", ".join(f"int p{i}" for i in range(nparams))
    args = []
    for k, v in pushes:
        args.append(f"p{(v - 6) // 2}" if k == "param" else str(v))
    fn = "w_" + va.replace(":", "_")
    # pascal puts the FIRST declared parameter at the highest frame offset, so
    # offset n maps to p[nparams-1-(n-6)//2], not (n-6)//2.
    args = []
    for k, v in pushes:
        args.append(f"p{nparams - 1 - (v - 6) // 2}" if k == "param" else str(v))
    callee = "CALLEE%d" % len(pushes)
    lines.append(f"void __far __pascal {fn}({names})\n{{\n    {callee}({', '.join(args)});\n}}")
    meta.append((va, size, fn, len(pushes)))
    stubs.add(len(pushes))

protos = "".join(f'void __near __pascal CALLEE{n}({", ".join(["int"] * n)});\n' for n in sorted(stubs))
bodies = "".join(f'void __near __pascal CALLEE{n}({", ".join(f"int q{i}" for i in range(n))}) {{ }}\n'
                 for n in sorted(stubs))
src = ("/* generated by tools/wraps.py - thin far-call wrappers */\n" + protos + "\n"
       + "\n\n".join(lines) + "\n\n" + bodies)
target = os.path.join(ROOT, "src", "calib", "cwraps.c")
if os.path.isfile(target) and "src/calib/cwraps.c" in ledger:
    sys.exit("refusing to overwrite src/calib/cwraps.c: the ledger references it")
open(target, "w", encoding="ascii").write(src)

r = subprocess.run([sys.executable, os.path.join(ROOT, "build.py"), "src/calib/cwraps.c",
                    "--flags", FLAGS, "--force"], capture_output=True, text=True)
print((r.stdout or "").strip().splitlines()[-1] if r.stdout else "", (r.stderr or "")[-300:])
obj = os.path.join(ROOT, "build", "cwraps.OBJ")
ok, rows = 0, []
for va, size, fn, n in meta:
    q = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "match.py"), va, fn.upper(),
                        "--obj", obj, "--size", str(size)], capture_output=True, text=True)
    good = q.returncode == 0
    ok += good
    if not good:
        msg = ((q.stdout or "") + (q.stderr or "")).strip().splitlines()
        print(f"  {va} {fn.upper()}: DIFF  {msg[1] if len(msg) > 1 else msg[0] if msg else ''}")
    else:
        rows.append(f'| {va} | {fn.upper()} | {size} | RELOCS | src=src/calib/cwraps.c; '
                    f'flags="{FLAGS}"; wrapper family ({n} pushed argument(s)) |')
print(f"\n{ok}/{len(meta)} verified")
print("\n".join(rows))
