#!/usr/bin/env python3
"""relays.py — generator for the LINK-/F relay family (see docs/CONVENTIONS.md).

Finds unmatched functions of the shape

    55 8B EC <word pushes> 90 0E E8 rel16 C9 (CA|C2) imm16

i.e. a framed Pascal function that pushes N words and calls one far function,
where the linker rewrote the call into NOP; PUSH CS; CALL NEAR. It emits the C
(`src/calib/<stem>.c`), builds it once, matches every member and prints ready
ledger rows.

Usage: python tools/relays.py [--stem crely7] [--flags "/G1 /AM /Gs /Os"] [--write]
"""
import argparse
import csv
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = open(os.path.join(ROOT, "..", "giten", "DDS98", "DDS98.EXE"), "rb").read()[896 * 16:339735]
PY = sys.executable

PUSH = rb"(?:\xff\x76(?P<disp>[\x04-\x20])|\x6a(?P<i8>.)|\x68(?P<i16>..))"
RELAY = re.compile(rb"\x55\x8b\xec(?P<pushes>" + PUSH + rb"+)\x90\x0e\xe8..\xc9(?P<ret>\xca|\xc2)(?P<imm>..)")
PUSH_RE = re.compile(PUSH)


def ledger_done():
    text = open(os.path.join(ROOT, "docs", "MATCHING.md"), encoding="utf-8").read()
    return {int(m.group(1), 16) * 16 + int(m.group(2), 16)
            for m in re.finditer(r"^\|\s*([0-9a-f]{4}):([0-9a-f]{4})\s*\|", text, re.M)}


def candidates():
    """[(va, lin, length, pushes)] for unmatched members of the family."""
    crt = {int(r["linear"], 16) for r in csv.DictReader(
        open(os.path.join(ROOT, "ground_truth", "foreign_crt.csv")))}
    done = ledger_done()
    units = {}
    for r in csv.DictReader(open(os.path.join(ROOT, "ground_truth", "units.csv"))):
        lin = int(r["linear"], 16)
        units.setdefault(lin, (r["va"], int(r["size"])))
    out = []
    for lin, (va, size) in units.items():
        if lin in done or lin in crt:
            continue
        b = IMG[lin - 0x10000: lin - 0x10000 + size]
        m = RELAY.match(b)
        if not m:
            continue
        nargs = int.from_bytes(m.group("imm"), "little") // 2
        pushes = []
        for pm in PUSH_RE.finditer(m.group("pushes")):
            if pm.group("disp"):
                off = pm.group("disp")[0]
                idx_from_last = (off - 6) // 2
                if off < 6 or (off - 6) % 2 or idx_from_last > nargs - 1:
                    pushes = None
                    break
                pushes.append(("param", nargs - 1 - idx_from_last))
            elif pm.group("i8"):
                pushes.append(("const", int.from_bytes(pm.group("i8"), "little", signed=True)))
            else:
                pushes.append(("const", int.from_bytes(pm.group("i16"), "little", signed=True)))
        if not pushes:
            continue
        out.append((va, lin, m.end(), nargs, pushes))
    out.sort(key=lambda t: t[1])
    return out


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--stem", default="crely7", help="source stem in src/calib (8.3)")
    ap.add_argument("--flags", default="/G1 /AM /Gs /Os")
    ap.add_argument("--write", action="store_true", help="write rows into docs/MATCHING.md")
    a = ap.parse_args()
    if len(a.stem) > 8:
        sys.exit("ERROR: stem must be 8.3 (max 8 characters)")
    src_rel = f"src/calib/{a.stem}.c"
    if src_rel in open(os.path.join(ROOT, "docs", "MATCHING.md"), encoding="utf-8").read():
        sys.exit(f"ERROR: {src_rel} is already referenced by the ledger")

    rows = candidates()
    print(f"# {len(rows)} relay functions ({sum(r[2] for r in rows)} B) for {src_rel}")
    if not rows:
        return

    names, decl, funcs, sigs = [], [], [], {}
    for (va, _lin, _ln, nargs, pushes) in rows:
        name = "F_" + va.replace(":", "_").upper()
        names.append(name)
        sigs[nargs] = sigs.get(nargs, 0) + 1
        params = ", ".join(f"int p{i}" for i in range(nargs))
        args = ", ".join((f"p{i}" if kind == "param" else str(i)) for kind, i in pushes)
        decl.append(f"int __far __pascal Sub{nargs}({params});")
        funcs.append(f"int __far __pascal {name}({params}) {{ return Sub{nargs}({args}); }}")
    hdr = "/* generated by tools/relays.py: LINK-/F relay family (see CONVENTIONS.md) */\n"
    src = hdr + "\n".join(sorted(set(decl))) + "\n\n" + "\n".join(funcs) + "\n"
    path = os.path.join(ROOT, src_rel)
    open(path, "w", encoding="ascii", newline="\n").write(src)

    r = subprocess.run([PY, os.path.join(ROOT, "build.py"), src_rel, "--flags", a.flags, "--force"],
                       capture_output=True, text=True)
    if r.returncode != 0:
        sys.exit("BUILD FAILED\n" + (r.stdout or "")[-500:] + (r.stderr or "")[-500:])
    obj = os.path.join(ROOT, "build", a.stem + ".OBJ")

    out = []
    for (va, _lin, length, nargs, pushes) in rows:
        name = "F_" + va.replace(":", "_").upper()
        desc = ", ".join((f"p{i}" if kind == "param" else str(i)) for kind, i in pushes)
        q = subprocess.run([PY, os.path.join(ROOT, "tools", "match.py"), va, name,
                            "--obj", obj, "--size", str(length)], capture_output=True, text=True)
        line = (q.stdout or q.stderr).strip().splitlines()[0] if (q.stdout or q.stderr) else "?"
        status = "RELOCS" if "RELOCS" in line else "MATCH" if "MATCH" in line else None
        if status:
            out.append((va, name, length, status, desc))
            print(f"  {va} {name}: {status}")
        else:
            print(f"  {va} {name}: SKIP ({line})")
    print(f"\n# {len(out)} verified rows")
    for va, name, length, status, desc in out:
        print(f"| {va} | {name} | {length} | {status} | src={src_rel}; flags=\"{a.flags}\"; "
              f"relay `Sub({desc})`; image `90 0E E8` = LINK /F translation of the object's `9A` |")
    if a.write and out:
        text = open(os.path.join(ROOT, "docs", "MATCHING.md"), encoding="utf-8").read().rstrip("\n")
        add = []
        for va, name, length, status, desc in out:
            add.append(f"| {va} | {name} | {length} | {status} | src={src_rel}; flags=\"{a.flags}\"; "
                       f"relay `Sub({desc})`; image `90 0E E8` = LINK /F translation of the object's `9A` |")
        open(os.path.join(ROOT, "docs", "MATCHING.md"), "w", encoding="utf-8", newline="\n").write(
            text + "\n" + "\n".join(add) + "\n")
        print(f"# appended {len(add)} rows to docs/MATCHING.md")


if __name__ == "__main__":
    main()
