#!/usr/bin/env python3
"""report.py — creates docs/STATUS.md from the ledger + coverage (template phase 6).

Counters are never written from memory: the ledger is the source for
MATCH/RELOCS/PENDING, coverage.compute() for the byte metric. The hand-written
part of STATUS.md (open points, toolchain notes) sits between the markers
MANUAL-BEGIN/MANUAL-END and stays untouched."""
import datetime
import os

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
import sys

sys.path.insert(0, os.path.join(ROOT, "tools"))
import coverage  # noqa: E402

STATUS = os.path.join(ROOT, "docs", "STATUS.md")


def keep_manual(path):
    if not os.path.isfile(path):
        return ""
    text = open(path, encoding="utf-8").read()
    if "<!-- MANUAL-BEGIN -->" not in text:
        return ""
    manual = text.split("<!-- MANUAL-BEGIN -->", 1)[1]
    manual = manual.split("<!-- MANUAL-END -->", 1)[0]
    return manual.strip("\n")


def main():
    s = coverage.compute()
    today = datetime.date.today().isoformat()
    pct = f"{100 * s['ok_b'] / s['eig_b']:.3f}%" if s["eig_b"] else "-"

    lines = [
        "# STATUS",
        "",
        f"<!-- GENERATED by tools/report.py on {today} — numbers not by hand -->",
        "<!-- Hand-written part between MANUAL-BEGIN and MANUAL-END is preserved. -->",
        "",
        "## Ledger (source: docs/MATCHING.md)",
        "",
        "| Status | Count |",
        "|---|---|",
        f"| MATCH | {s['n_match']} |",
        f"| RELOCS | **{s['n_relocs']}** |",
        f"| ASM (excluded from C coverage) | {sum(row[3] == 'ASM' for row in s['ledger'].values())} |",
        f"| PENDING | **{s['n_pending']}** |",
        "",
        "PENDING cases (details in `docs/MATCHING.md`, idioms in `docs/IDIOMS.md`):",
        "",
    ]
    pend = [(v[0], v[1], v[2], v[4]) for v in s["ledger"].values() if v[3] == "PENDING"]
    if not pend:
        lines.append("_(none)_")
    for va, name, size, note in pend:
        short = note.split(";")[0][:150]
        lines.append(f"- `{va}` **{name}** ({size} B) — {short}")
    lines += [
        "",
        "## Coverage (honest byte metric)",
        "",
        "| Category | Value |",
        "|---|---|",
        f"| Inventory entries | **{s['tot_f']}** code functions + **{s['n_data']}** data |",
        f"| Data (proven, `not_code.csv`) | {s['nc_b']} B |",
        f"| Code bytes | {s['tot_b']} |",
        f"| − Foreign CRT (signatures) | {s['fremd_b']} |",
        f"| = **Own code bytes** | **{s['eig_b']}** |",
        f"| of which **verified** | **{s['ok_b']} ({pct})** |",
        f"| PENDING bytes | {s['pend_b']} |",
        "",
        f"Code functions: **{s['tot_f']}**, of which verified **{s['ok_f']}**.",
        "",
        "## Regions (64 KiB)",
        "",
        "| Region | Functions | ok | Code-B | verified | CRT | Data | PENDING |",
        "|---|---|---|---|---|---|---|---|",
    ]
    for reg in sorted(s["regions"]):
        d = s["regions"][reg]
        eig = d["total"] - d["fremd"]
        rp = f"{100 * d['matched'] / eig:.1f}%" if eig > 0 else "-"
        lines.append(f"| {reg:#06x} | {d['n']} | {d['nm']} | {d['total']} | "
                     f"{d['matched']} ({rp}) | {d['fremd']} | {d['notcode']} | {d['pend']} |")

    manual = keep_manual(STATUS)
    lines += [
        "",
        "<!-- MANUAL-BEGIN -->",
        manual if manual else DEFAULTS,
        "<!-- MANUAL-END -->",
        "",
    ]
    with open(STATUS, "w", encoding="utf-8") as f:
        f.write("\n".join(lines))
    print(f"STATUS.md written: {os.path.relpath(STATUS, ROOT)} "
          f"(ledger {s['n_relocs']} RELOCS / {s['n_pending']} PENDING, "
          f"{pct} own bytes verified)")


DEFAULTS = """## Toolchain

- **MSC 7.0 (CL 8.00, 1992)**: dosbox-x + HDPMI32 TSR, `-nopromptfolder`,
  APPDATA redirect, `cycles=max` — recipe in `docs/CONVENTIONS.md`.
- CFLAGS **confirmed: `/G1 /AM /Gs /Os`** (byte-identical calibration functions).

## Open (order for the next rounds)

1. `LINK.EXE` (DOSX16) hangs under dosbox-x in all DPMI variants — prerequisite
   for `build_replacement` (phase 6); candidate: native OMF linker (jwlink)
2. Slot subsystem: consider `__asm` reconstruction (C is provably exhausted there)
3. Continue the family workflow: ALU/DOS helpers with `55 8b ec` frame"""


if __name__ == "__main__":
    main()
