"""Generate every swap-and-return member (round 66).

   55 8B EC / 8B 16 <g> / 8B 46 <04|06> / A3 <g> / 8B C2 / C9 <CA|C2> 02 00 (00)
Offset 06 = far pascal (first argument at bp+6), 04 = near pascal. A trailing
00 byte is padding, so the function length is 19.
"""
import csv
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = open(os.path.join(ROOT, "..", "giten", "DDS98", "DDS98.EXE"), "rb").read()[896 * 16:339735]
FLAGS = "/G1 /AM /Gs /Ox /Oa /Os"

units = {int(r["linear"], 16): (r["va"], int(r["size"]))
         for r in csv.DictReader(open(os.path.join(ROOT, "ground_truth", "units.csv")))}
ledger = open(os.path.join(ROOT, "docs", "MATCHING.md"), encoding="utf-8").read()
done = {int(m.group(1), 16) * 16 + int(m.group(2), 16)
        for m in re.finditer(r"^\|\s*([0-9a-f]{4}):([0-9a-f]{4})\s*\|", ledger, re.M)}

PAT = re.compile(rb"\x55\x8B\xEC\x8B\x16(?P<g>..)\x8B\x46(?P<off>\x04|\x06)"
                 rb"\xA3(?P<g2>..)\x8B\xC2\xC9(?P<ret>\xCA|\xC2)\x02\x00\x00?", re.S)

hits = []
for lin, (va, size) in units.items():
    if lin in done:
        continue
    b = IMG[lin - 0x10000: lin - 0x10000 + size]
    m = PAT.fullmatch(b) if b else None
    if not m or m.group("g") != m.group("g2"):
        continue
    hits.append((va, int.from_bytes(m.group("g"), "little"), m.group("off") == b"\x06"))

print(f"{len(hits)} swap-and-return units")
lines, meta = [], []
for va, g, isfar in hits:
    gname = "g_%04x" % g
    lines.append(f"int {gname};")
lines.append("")
for va, g, isfar in hits:
    fn = "x_" + va.replace(":", "_")
    conv = "__far __pascal" if isfar else "__near __pascal"
    lines.append(f"int {conv} {fn}(int v)\n{{\n    int old = g_{g:04x};\n\n"
                 f"    g_{g:04x} = v;\n    return old;\n}}")
    meta.append((va, fn))

src = "/* generated by tools/swapgen.py - swap-and-return family */\n" + "\n".join(lines) + "\n"
target = os.path.join(ROOT, "src", "calib", "cswap4.c")
if os.path.isfile(target) and "src/calib/cswap4.c" in ledger:
    sys.exit("refusing to overwrite cswap4.c: the ledger references it")
open(target, "w", encoding="ascii").write(src)

r = subprocess.run([sys.executable, os.path.join(ROOT, "build.py"), "src/calib/cswap4.c",
                    "--flags", FLAGS, "--force"], capture_output=True, text=True)
print((r.stdout or "").strip().splitlines()[-1] if r.stdout else "", (r.stderr or "")[-300:])
obj = os.path.join(ROOT, "build", "cswap4.OBJ")
ok, rows = 0, []
for va, fn in meta:
    q = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "match.py"), va, fn.upper(),
                        "--obj", obj, "--size", "19"], capture_output=True, text=True)
    good = q.returncode == 0
    ok += good
    if good:
        rows.append(f'| {va} | {fn.upper()} | 19 | RELOCS | src=src/calib/cswap4.c; '
                    f'flags="{FLAGS}"; swap-and-return family (generated) |')
    else:
        msg = ((q.stdout or "") + (q.stderr or "")).strip().splitlines()
        print(f"  {va}: DIFF {msg[1] if len(msg) > 1 else ''}")
print(f"{ok}/{len(meta)} verified")
print("\n".join(rows))
