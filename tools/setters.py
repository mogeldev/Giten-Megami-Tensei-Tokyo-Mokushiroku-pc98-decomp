"""Sweep far-pascal store-setters at unit boundaries and match them automatically.

Shape:  55 8B EC (8B 46 xx A3 <disp16>)+ (C7 06 <disp16> <imm16>)? C9 CA/C2 imm16
For k stores the parameters live at bp+6 .. bp+6+2(k-1), highest offset first
(pascal pushes left to right), so the generated source assigns them in the byte
order of the stores.
"""
import csv
import os
import re
import subprocess
import sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
IMG = open(os.path.join(ROOT, "..", "giten", "DDS98", "DDS98.EXE"), "rb").read()[896 * 16:339735]
FLAGS = "/G1 /AM /Gs /Os"

units = {int(r["linear"], 16): (r["va"], int(r["size"]))
         for r in csv.DictReader(open(os.path.join(ROOT, "ground_truth", "units.csv")))}
ledger = open(os.path.join(ROOT, "docs", "MATCHING.md"), encoding="utf-8").read()
done = {int(m.group(1), 16) * 16 + int(m.group(2), 16)
        for m in re.finditer(r"^\|\s*([0-9a-f]{4}):([0-9a-f]{4})\s*\|", ledger, re.M)}

PAT = re.compile(rb"\x55\x8B\xEC"
                 rb"((?:\x8B\x46.\xA3..){1,6})"
                 rb"(?:\xC7\x06(?P<id>..)(?P<ii>..))?"
                 rb"\xC9(?:\xCA|\xC2)(?P<ret>..)", re.S)

hits = []
for lin, (va, size) in units.items():
    if lin in done:
        continue
    b = IMG[lin - 0x10000: lin - 0x10000 + size]
    m = PAT.match(b) if b else None          # prefix match: trailing padding is allowed
    if m and (b[m.end():].strip(b"\x00\x90")):
        m = None                            # ... but only real padding (00/90)
    if not m:
        continue
    stores = [m.group(1)[i:i + 7] for i in range(0, len(m.group(1)), 7)]
    pairs = [(int.from_bytes(s[2:4], "little"), int.from_bytes(s[4:6], "little")) for s in stores]
    hits.append((va, m.end(), pairs, m.group("id"), m.group("ii"), m.group("ret")))

print(f"{len(hits)} store-setter units")
if not hits:
    sys.exit(0)

decls, funcs, meta = [], [], []
for i, (va, size, pairs, iid, iii, ret) in enumerate(hits):
    k = len(pairs)
    args = ", ".join(f"int a{j}" for j in range(k))
    body = []
    for j, (disp, imm) in enumerate(pairs):
        gname = f"g_{disp:04x}"
        if f"int {gname};" not in decls:
            decls.append(f"int {gname};")
        body.append(f"    {gname} = a{j};")
    if iid:
        d = int.from_bytes(iid, "little"); v = int.from_bytes(iii, "little")
        gname = f"g_{d:04x}"
        if f"int {gname};" not in decls:
            decls.append(f"int {gname};")
        body.append(f"    {gname} = {v};")
    fn = "set_" + va.replace(":", "_")
    funcs.append(f"void __far __pascal {fn}({args})\n{{\n" + "\n".join(body) + "\n}")
    meta.append((va, size, fn))

src = "/* generated by tools/setters.py - far-pascal store setters */\n" + "\n".join(decls) + "\n\n" + "\n\n".join(funcs) + "\n"
target = os.path.join(ROOT, "src", "calib", "cset8.c")
# Refuse to clobber a source the ledger depends on (round 59: a generator with a
# name collision silently overwrote a verified calibration file).
if os.path.isfile(target) and "src/calib/cset8.c" in ledger:
    sys.exit("refusing to overwrite src/calib/cset8.c: the ledger references it")
open(target, "w", encoding="ascii").write(src)
r = subprocess.run([sys.executable, os.path.join(ROOT, "build.py"), "src/calib/cset8.c",
                    "--flags", FLAGS, "--force"], capture_output=True, text=True)
print((r.stdout or "").strip().splitlines()[-1] if r.stdout else "", (r.stderr or "")[-300:])
obj = os.path.join(ROOT, "build", "cset8.OBJ")
ok = 0
rows = []
for va, size, fn in meta:
    q = subprocess.run([sys.executable, os.path.join(ROOT, "tools", "match.py"), va, fn.upper(),
                        "--obj", obj, "--size", str(size)], capture_output=True, text=True)
    good = q.returncode == 0
    ok += good
    print(f"  {va} {fn.upper()}: {'RELOCS' if good else 'DIFF'}")
    if not good:
        print("    " + ((q.stdout or "") + (q.stderr or "")).strip()[:200])
    else:
        rows.append(f'| {va} | {fn.upper()} | {size} | RELOCS | src=src/calib/cset8.c; '
                    f'flags="{FLAGS}"; generated store-setter |')
print(f"\n{ok}/{len(meta)} verified")
print("\n".join(rows))
